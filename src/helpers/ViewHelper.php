    /**
     * Formatea precio con separadores de miles colombianos
     */
    public static function formatPrice(string $price): string
    {
        return SecurityHelper::escape($price);
    }

    /**
     * Genera clases CSS para tarjeta según color de servicio
     */
    public static function getServiceCardClass(array $service): string
    {
        $isPremium = $service['premium'] ?? false;
        return $isPremium ? 'service-card service-card--premium' : 'service-card';
    }

    /**
     * Genera el input hidden CSRF para formularios
     */
    public static function csrfField(): string
    {
        $token = SecurityHelper::generateCsrfToken();
        return sprintf(
            '<input type="hidden" name="csrf_token" value="%s">',
            SecurityHelper::escape($token)
        );
    }
